-- ---------------------------------------------------------------------------
-- updated_at triggers
-- ---------------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array[
    'sessions','session_blocks','snatch_blocks','calisthenics_entries',
    'hypertrophy_sets','injuries','injury_observations','daily_metrics'
  ] loop
    execute format('drop trigger if exists touch_%1$s on fitness.%1$s', t);
    execute format(
      'create trigger touch_%1$s before update on fitness.%1$s
       for each row execute function fitness.touch_updated_at()', t);
  end loop;
end $$;

-- ---------------------------------------------------------------------------
-- Views. Success rates draw on substantiated full-lift blocks only.
-- ---------------------------------------------------------------------------
create or replace view fitness.v_snatch_blocks as
select b.id, b.session_id, s.session_date, s.gym_id, g.name as gym_name,
       v.slug as variation, v.counts_as_full_lift,
       b.weight_kg, b.sets_count, b.reps_per_set, b.attempts,
       b.full_stand_successes, b.received_not_stood, b.dropped, b.received_total,
       b.quality_10, b.straps, f.slug as failure_mode,
       b.is_warmup, b.is_cooldown, b.notes,
       b.provenance, b.record_precision, b.record_quality, b.is_substantiated,
       fitness.week_start(s.session_date) as week_start
  from fitness.snatch_blocks b
  join fitness.sessions s           on s.id = b.session_id
  join fitness.snatch_variations v  on v.id = b.variation_id
  left join fitness.gyms g          on g.id = s.gym_id
  left join fitness.failure_modes f on f.id = b.failure_mode_id;

create or replace view fitness.v_snatch_success_by_weight as
select weight_kg,
       count(*)                            as blocks,
       sum(attempts)                       as attempts,
       sum(full_stand_successes)           as stood,
       sum(coalesce(received_not_stood,0)) as received_not_stood,
       sum(coalesce(received_total,0))     as received,
       round(100.0 * sum(full_stand_successes) / nullif(sum(attempts),0), 1) as stand_rate_pct,
       -- Receiving the bar and standing it are different capabilities. Reading
       -- these two side by side is what shows whether the catch or the stand
       -- is the current limiter.
       round(100.0 * sum(coalesce(received_total,0)) / nullif(sum(attempts),0), 1) as receive_rate_pct
  from fitness.v_snatch_blocks
 where is_substantiated and counts_as_full_lift
 group by weight_kg
 order by weight_kg;

create or replace view fitness.v_snatch_weekly as
select week_start, weight_kg,
       sum(attempts)             as attempts,
       sum(full_stand_successes) as stood,
       round(100.0 * sum(full_stand_successes) / nullif(sum(attempts),0), 1) as stand_rate_pct
  from fitness.v_snatch_blocks
 where is_substantiated and counts_as_full_lift
 group by week_start, weight_kg
 order by week_start desc, weight_kg;

create or replace view fitness.v_session_summary as
select s.id, s.session_date, coalesce(g.name, s.gym_custom_label) as gym,
       s.started_at, s.ended_at,
       (select array_agg(distinct sb.workstream::text order by sb.workstream::text)
          from fitness.session_blocks sb where sb.session_id = s.id) as workstreams,
       (select count(*) from fitness.snatch_blocks x       where x.session_id = s.id) as snatch_blocks,
       (select count(*) from fitness.hypertrophy_sets x     where x.session_id = s.id) as hypertrophy_sets,
       (select count(*) from fitness.calisthenics_entries x where x.session_id = s.id) as calisthenics_entries,
       s.notes, s.provenance
  from fitness.sessions s
  left join fitness.gyms g on g.id = s.gym_id
 order by s.session_date desc;

-- ---------------------------------------------------------------------------
-- Row level security.
-- The site is public and READ-ONLY to the world. Every write goes through a
-- server route holding the service-role key, which bypasses RLS. The anon key
-- is browser-safe only because of these policies.
-- ---------------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array[
    'gyms','snatch_variations','snatch_weight_presets','failure_modes','snatch_tags',
    'muscle_groups','exercises','exercise_aliases','skills','skill_variations',
    'assistance_types','provoking_activities','sessions','session_blocks',
    'snatch_blocks','snatch_attempts','snatch_block_tags','snatch_attempt_tags',
    'calisthenics_entries','hypertrophy_sets','injuries','injury_observations',
    'daily_metrics','import_batches','import_records','settings'
  ] loop
    execute format('alter table fitness.%I enable row level security', t);
    execute format('drop policy if exists public_read on fitness.%I', t);
    execute format(
      'create policy public_read on fitness.%I for select to anon, authenticated using (true)', t);
  end loop;
end $$;

-- Staging rows are working notes holding conflicting counts; they should not be
-- readable as though they were results.
drop policy if exists public_read on fitness.import_records;
drop policy if exists public_read on fitness.import_batches;

grant usage on schema fitness to anon, authenticated;
grant select on all tables in schema fitness to anon, authenticated;
revoke select on fitness.import_records, fitness.import_batches from anon, authenticated;
alter default privileges in schema fitness grant select on tables to anon, authenticated;

