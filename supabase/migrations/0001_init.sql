  create type fitness.snatch_order as enum ('before_snatch', 'after_snatch', 'standalone', 'unknown');
exception when duplicate_object then null; end $$;

do $$ begin
  create type fitness.import_status as enum ('pending_review', 'imported', 'rejected', 'superseded');
exception when duplicate_object then null; end $$;

do $$ begin
  create type fitness.change_direction as enum ('better', 'same', 'worse', 'unknown');
