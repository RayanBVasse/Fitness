-- Keep block counters derived wherever per-attempt rows exist.
create or replace function fitness.sync_snatch_block_counts()
returns trigger language plpgsql as $$
declare
  target  uuid := coalesce(new.block_id, old.block_id);
  n_total int;
begin
  -- Aborted attempts are not lifts, so they never enter the denominator.
  select count(*) into n_total
    from fitness.snatch_attempts
   where block_id = target and outcome <> 'aborted';

  if n_total = 0 then
    -- Last attempt removed: leave stored counts alone, so a block reverted to
    -- historical entry is not silently zeroed.
    return null;
  end if;

  update fitness.snatch_blocks b
     set attempts             = n_total,
         full_stand_successes = (select count(*) from fitness.snatch_attempts a
                                  where a.block_id = target and a.outcome = 'stood'),
         received_not_stood   = (select count(*) from fitness.snatch_attempts a
                                  where a.block_id = target and a.outcome = 'received_not_stood'),
         -- All attempts that failed to stand, received or not, matching the
         -- historical column's meaning.
         dropped              = (select count(*) from fitness.snatch_attempts a
                                  where a.block_id = target
                                    and a.outcome in ('received_not_stood', 'missed')),
         record_precision     = 'attempt',
         updated_at           = now()
   where b.id = target;
  return null;
end $$;

drop trigger if exists snatch_attempts_sync on fitness.snatch_attempts;
create trigger snatch_attempts_sync
after insert or update or delete on fitness.snatch_attempts
for each row execute function fitness.sync_snatch_block_counts();

