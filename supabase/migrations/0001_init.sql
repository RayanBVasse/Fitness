-- ============================================================================
-- Fitness Observatory — schema init
-- Target: living-literature Supabase project, dedicated schema `fitness`
-- Run this in the Supabase SQL editor. Safe to re-run.
--
-- Design notes this schema encodes deliberately:
--   * A gym visit is ONE session containing N workstream blocks, each with its
--     own editable start/end times. Three workstreams: snatch, calisthenics,
--     hypertrophy. Injuries are a cross-cutting category, not a workstream.
--   * Snatch outcome has THREE states. "Received but not stood" is neither a
--     success nor a miss; it was the dominant failure mode in Jan 2026 and is
--     the most informative field in the 50 kg history.
--   * Load success and technical quality are separate columns. Nothing derives
--     quality from outcome.
--   * Machine identity is (gym, exercise), narrowed by machine_label where a
--     gym has two of the same machine. 55 kg on Ealing's pendulum squat is not
--     55 kg on another gym's.
--   * Historical reconstruction rows are marked, never silently repaired, and
--     excluded from precision metrics unless both numerator and denominator
--     are present (is_substantiated).
-- ============================================================================

create schema if not exists fitness;

-- ---------------------------------------------------------------------------
-- Enumerated types
-- ---------------------------------------------------------------------------
do $$ begin
  create type fitness.workstream as enum ('snatch', 'calisthenics', 'hypertrophy');
exception when duplicate_object then null; end $$;

-- Per-attempt outcome, mutually exclusive:
--   stood              — received overhead and stood up. The only success.
--   received_not_stood — caught it, never stood it. Neither success nor miss.
--   missed             — never received.
--   aborted            — abandoned before receiving. Not a lift at all.
do $$ begin
  create type fitness.snatch_outcome as enum ('stood', 'received_not_stood', 'missed', 'aborted');
exception when duplicate_object then null; end $$;

-- Where a row came from. Drives chart styling and metric eligibility.
do $$ begin
  create type fitness.provenance as enum ('logged', 'workbook_import', 'historical_reconstruction');
exception when duplicate_object then null; end $$;

-- How exact a row is. 'block' rows carry aggregate counts (historical);
-- 'attempt' rows are precise, live-tapped records.
do $$ begin
  create type fitness.record_precision as enum ('attempt', 'block', 'qualitative');
exception when duplicate_object then null; end $$;

do $$ begin
  create type fitness.body_side as enum ('both', 'left', 'right');
exception when duplicate_object then null; end $$;

-- Order relative to the snatch work in the same session. This is the
-- interference variable; the August workbook records it on every row.
