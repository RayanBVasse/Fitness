-- ---------------------------------------------------------------------------
-- Workstream A — snatch
-- The weight block is the canonical unit: it is how the lifting is actually
-- recorded, and the only shape the historical data supports. Live rapid-tap
-- logging writes snatch_attempts rows and a trigger keeps the block counters
-- in sync, so attempts stay the single source of truth where they exist.
-- ---------------------------------------------------------------------------
create table if not exists fitness.snatch_blocks (
  id                   uuid primary key default gen_random_uuid(),
  session_id           uuid not null references fitness.sessions(id) on delete cascade,
  session_block_id     uuid references fitness.session_blocks(id) on delete set null,
  variation_id         smallint not null references fitness.snatch_variations(id),
  weight_kg            numeric(5,2),
  sets_count           smallint,
  reps_per_set         smallint,
  attempts             smallint,
  full_stand_successes smallint,
  -- Received overhead but not stood up. NOT mutually exclusive with `dropped`:
  -- a lift can be received and then dropped. The 2026-05-30 row is the proof —
  -- 7 attempts, 3 stood, 4 drops, 3 received-not-stood, and the source's own
  -- summary reads "3/7 full stand, receiving 6/7". So received_total is
  -- stood + received_not_stood, and drops overlap it.
  received_not_stood   smallint,
  -- Every attempt that failed to stand, whether or not it was received. A
  -- superset of received_not_stood, which is why it is not summed alongside it.
  dropped              smallint,
  received_total       smallint generated always as
                         (case when attempts is null then null
                               else coalesce(full_stand_successes,0) + coalesce(received_not_stood,0)
                          end) stored,
  quality_10           smallint check (quality_10 between 1 and 10),
  rpe_10               numeric(3,1) check (rpe_10 between 1 and 10),
  straps               boolean,
  failure_mode_id      smallint references fitness.failure_modes(id),
  is_warmup            boolean not null default false,
  is_cooldown          boolean not null default false,
  notes                text,
  logged_at            timestamptz,
  provenance           fitness.provenance not null default 'logged',
  record_precision     fitness.record_precision not null default 'attempt',
  record_quality       text,
  source_record_id     text,
  -- Only blocks with both numerator and denominator may feed success rates.
  is_substantiated     boolean generated always as
                         (attempts is not null and full_stand_successes is not null) stored,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  -- Counts must reconcile, but only once present. Historical rows with blanks
  -- are left alone rather than coerced to zero. `dropped` is deliberately NOT
  -- summed in: a received-then-dropped attempt is counted in both columns.
  constraint snatch_counts_reconcile check (
    attempts is null
    or (coalesce(full_stand_successes,0) + coalesce(received_not_stood,0) <= attempts
        and coalesce(dropped,0) <= attempts)
  )
);
create index if not exists snatch_blocks_session_idx on fitness.snatch_blocks (session_id);
create index if not exists snatch_blocks_weight_idx  on fitness.snatch_blocks (weight_kg);

