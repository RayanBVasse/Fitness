-- ---------------------------------------------------------------------------
-- Helpers. Everything reports on Europe/London Monday-Sunday weeks.
-- ---------------------------------------------------------------------------
create or replace function fitness.london_today()
returns date language sql stable as $$
  select (now() at time zone 'Europe/London')::date;
$$;

create or replace function fitness.london_date(ts timestamptz)
returns date language sql immutable as $$
  select (ts at time zone 'Europe/London')::date;
$$;

create or replace function fitness.week_start(d date)
returns date language sql immutable as $$
  select (d - ((extract(isodow from d)::int - 1) || ' days')::interval)::date;
$$;

create or replace function fitness.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

