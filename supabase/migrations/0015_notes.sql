-- ============================================================================
-- Fitness Observatory — authored notes, third-party aliases, and the fold
--
-- Three things, one migration:
--
--   1. `third_parties`: the redaction list, moved out of code and into data.
--      It was three hardcoded patterns written for the names that happened to
--      appear in the imported pack. Other people turn up in gym notes all the
--      time and a redeploy is the wrong unit of work for adding one.
--
--   2. `context_notes.workstream`: a note can belong to the snatch, the
--      calisthenics or the hypertrophy part of a visit. It is NOT a session
--      block — writing a note must never assert that a workstream was
--      trained, because blocks are what the analytics count.
--
--   3. The fold: the free-text dimensions of the daily check-in become notes.
--      Food, Gym notes, How did the gym feel? and Anything else were text
--      rows in `daily_metrics`, which is a table of measurements. They are
--      not measurements. Everything already written is copied across first,
--      then the dimensions are retired.
--
-- `rest_reason` deliberately does NOT fold. It carries the suggestion chips
-- the day editor renders for a rest day, and retiring it would take the rest
-- reason UI with it.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. Third parties.
--
-- `alias` is matched case-insensitively on word boundaries, longest first, so
-- "Miss T" is replaced before a bare "T" could be. `role` is what the Coach
-- sees. Nothing here is sent anywhere; this table is the thing that stops it.
-- ---------------------------------------------------------------------------
create table if not exists fitness.third_parties (
  id         smallint generated by default as identity primary key,
  alias      text not null unique,
  role       text not null,
  is_active  boolean not null default true,
  notes      text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint third_parties_alias_not_blank check (length(btrim(alias)) > 1)
);

drop trigger if exists touch_third_parties on fitness.third_parties;
create trigger touch_third_parties before update on fitness.third_parties
for each row execute function fitness.touch_updated_at();

alter table fitness.third_parties enable row level security;

insert into fitness.third_parties (alias, role, notes) values
  ('Rob',            'a trainer',      'From the imported pack.'),
  ('gym crush',      'an acquaintance','From the imported pack.'),
  ('Sri Lankan guy', 'a lifter',       'Described by nationality rather than named.'),
  ('Miss T',         'an acquaintance', null),
  ('Lee',            'an acquaintance', null)
on conflict (alias) do nothing;

-- ---------------------------------------------------------------------------
-- 2. A note can name its workstream.
-- ---------------------------------------------------------------------------
alter table fitness.context_notes
  add column if not exists workstream fitness.workstream;

create index if not exists context_notes_workstream_idx
  on fitness.context_notes (workstream, anchor_date desc);

-- ---------------------------------------------------------------------------
-- 3. The fold.
--
-- Copied, not moved: the `daily_metrics` rows stay where they are so that any
-- figure already derived from them does not change underneath. The check-in
-- simply stops offering the dimensions, and the text lives on as notes.
--
-- `external_source_id` makes this idempotent — running it twice imports
-- nothing the second time.
-- ---------------------------------------------------------------------------
insert into fitness.context_notes (
  external_source_id, note_type, category, content, anchor_date,
  source_type, evidence_status, sensitivity, review_status, reviewed_at,
  content_hash, tags
)
select
  'checkin:' || m.metric_date::text || ':' || m.metric,
  'athlete_report',
  case m.metric
    when 'nutrition_note'  then 'nutrition'
    when 'gym_gossip'      then 'gym_context'
    when 'session_context' then 'gym_context'
    else 'observation'
  end,
  btrim(m.value_text),
  m.metric_date,
  'daily_check_in',
  'user_reported',
  'normal',
  -- The athlete wrote these in their own app. There is no third party to
  -- review them on behalf of, which is what `pending` is for.
  'approved',
  now(),
  md5(btrim(m.value_text)),
  array['check_in', m.metric]
from fitness.daily_metrics m
where m.metric in ('nutrition_note', 'gym_gossip', 'session_context', 'day_note')
  and m.value_text is not null
  and length(btrim(m.value_text)) > 0
on conflict (external_source_id) do nothing;

-- Retire the four dimensions. Both queries that build the check-in filter on
-- is_active, so this removes them from the screen without deleting history.
update fitness.daily_metric_defs
   set is_active = false
 where slug in ('nutrition_note', 'gym_gossip', 'session_context', 'day_note');

-- ---------------------------------------------------------------------------
-- Check.
-- ---------------------------------------------------------------------------
-- 1. What moved, by dimension.
select t.dimension, count(*)
  from fitness.context_notes n,
       lateral unnest(n.tags) as t(dimension)
 where n.source_type = 'daily_check_in'
   and t.dimension <> 'check_in'
 group by 1 order by 1;

-- 2. Nothing left behind: every non-empty text row should now have a note.
select m.metric, count(*) as metric_rows,
       count(n.id) as notes_created
  from fitness.daily_metrics m
  left join fitness.context_notes n
         on n.external_source_id = 'checkin:' || m.metric_date::text || ':' || m.metric
 where m.metric in ('nutrition_note', 'gym_gossip', 'session_context', 'day_note')
   and length(btrim(coalesce(m.value_text, ''))) > 0
 group by m.metric order by m.metric;

-- 3. The check-in should now offer rest_reason and no other text dimension.
select slug, label, is_active
  from fitness.daily_metric_defs
 where kind = 'text' order by slug;

-- 4. The redaction list.
select alias, role, is_active from fitness.third_parties order by length(alias) desc;
