"""
Generates the INSERT statements for fitness.context_notes from a review pack.

Run it against the pack's `context_notes_NEW_for_review.jsonl`:

    python scripts/build_context_notes_sql.py <notes.jsonl> <out.sql>

The output is NOT committed. These notes contain health details, named people
and private observations, and the pack's own contract says a private GitHub
repository is not the same as confidential. `private/` is gitignored; generate
there and paste the file into the Supabase SQL editor.

What this does NOT do, deliberately:

  * It never writes to sessions, snatch_blocks, hypertrophy_sets or
    calisthenics_entries. A note mentioning a 50 kg lift is a note. The lifts
    are already imported from the numeric staging pack, and counting them
    again from prose is how a success rate quietly doubles.
  * It never reads `structured_observation` as data. That field is carried
    across verbatim for a human reviewer and nothing else.
  * Every row lands as `pending`.

Re-running is safe: rows upsert on `external_source_id`, and a row whose
content has not changed is left completely alone, including its review status.
A changed note updates its content and is pushed back to `pending`, because a
decision made about different words is not a decision about these ones.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

NOTES = Path(sys.argv[1])
OUT = Path(sys.argv[2])


def q(value) -> str:
    """SQL literal."""
    if value is None or value == "":
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def text_array(values) -> str:
    if not values:
        return "'{}'"
    inner = ", ".join('"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"' for v in values)
    return "'{" + inner + "}'"


def jsonb(value) -> str:
    if value in (None, {}, []):
        return "null"
    return q(json.dumps(value, ensure_ascii=False, sort_keys=True)) + "::jsonb"


rows = [json.loads(line) for line in NOTES.read_text(encoding="utf-8").splitlines() if line.strip()]

seen: set[str] = set()
out: list[str] = []
w = out.append

w("-- ============================================================================")
w("-- Fitness Observatory — context notes import")
w("-- GENERATED by scripts/build_context_notes_sql.py. Do not commit this file.")
w("--")
w(f"-- {len(rows)} narrative notes into fitness.context_notes, all as `pending`.")
w("--")
w("-- Writes to no other table. These are observations and hypotheses, not")
w("-- measurements: the lifts they mention are already imported from the numeric")
w("-- staging pack, and counting them again from prose would double them.")
w("-- ============================================================================")
w("")
w("begin;")
w("")

for row in rows:
    external_id = row["source_id"]
    if external_id in seen:
        continue
    seen.add(external_id)

    content = (row.get("content") or "").strip()
    if not content:
        continue

    digest = hashlib.sha256(content.encode("utf-8")).hexdigest()[:32]

    w("insert into fitness.context_notes (")
    w("  external_source_id, note_type, category, content, anchor_date, period_label,")
    w("  source_type, source_timestamp, evidence_status, tags, structured_observation,")
    w("  candidate_numeric, sensitivity, content_hash")
    w(") values (")
    w(f"  {q(external_id)}, {q(row.get('note_type'))}, {q(row.get('category'))},")
    w(f"  {q(content)},")
    w(f"  {q(row.get('anchor_date'))}, {q(row.get('period'))},")
    w(f"  {q(row.get('source_type'))}, {q(row.get('source_timestamp'))}, {q(row.get('evidence_status'))},")
    w(f"  {text_array(row.get('tags'))}, {jsonb(row.get('structured_observation'))},")
    w(f"  {q(bool(row.get('candidate_numeric')))}, {q(row.get('sensitivity') or 'normal')}, {q(digest)}")
    w(")")
    w("on conflict (external_source_id) do update set")
    w("  content = excluded.content,")
    w("  note_type = excluded.note_type,")
    w("  category = excluded.category,")
    w("  anchor_date = excluded.anchor_date,")
    w("  period_label = excluded.period_label,")
    w("  source_type = excluded.source_type,")
    w("  source_timestamp = excluded.source_timestamp,")
    w("  evidence_status = excluded.evidence_status,")
    w("  tags = excluded.tags,")
    w("  structured_observation = excluded.structured_observation,")
    w("  candidate_numeric = excluded.candidate_numeric,")
    w("  sensitivity = excluded.sensitivity,")
    w("  content_hash = excluded.content_hash,")
    w("  -- A decision made about different words is not a decision about these.")
    w("  review_status = 'pending',")
    w("  reviewed_at = null,")
    w("  updated_at = now()")
    w("where fitness.context_notes.content_hash is distinct from excluded.content_hash;")
    w("")

w("-- ---------------------------------------------------------------------------")
w("-- Annotate, do not promote: link a note to that day's session where exactly")
w("-- one exists. This records that the note describes that day. It adds no")
w("-- attempt, set or success to it.")
w("-- ---------------------------------------------------------------------------")
w("update fitness.context_notes n")
w("   set linked_session_id = s.id")
w("  from fitness.sessions s")
w(" where n.anchor_date is not null")
w("   and n.linked_session_id is null")
w("   and s.session_date = n.anchor_date")
w("   and (select count(*) from fitness.sessions x where x.session_date = n.anchor_date) = 1;")
w("")
w("commit;")
w("")
w("-- Summary.")
w("select note_type, review_status, count(*) as rows,")
w("       count(*) filter (where candidate_numeric) as mention_numbers,")
w("       count(*) filter (where linked_session_id is not null) as linked_to_a_session")
w("  from fitness.context_notes")
w(" group by note_type, review_status")
w(" order by note_type;")
w("")
w("-- Nothing should have reached the performance tables. These counts must be")
w("-- unchanged: 79 sessions, 214 snatch blocks.")
w("select (select count(*) from fitness.sessions) as sessions,")
w("       (select count(*) from fitness.snatch_blocks) as snatch_blocks;")
w("")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")

anchored = sum(1 for r in rows if r.get("anchor_date"))
numeric = sum(1 for r in rows if r.get("candidate_numeric"))
print(f"notes read        : {len(rows)}")
print(f"written           : {len(seen)}")
print(f"anchored to a date: {anchored}")
print(f"mention numbers   : {numeric} (carried as hints, never as values)")
print(f"output            : {OUT}")
